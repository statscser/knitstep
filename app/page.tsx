function LoadingSkeleton() {
  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: 10 }}
      transition={{ duration: 0.3 }}
      className="no-print w-full max-w-xl p-8"
      style={{
        background:   "var(--bg-card)",
        border:       "1.5px solid var(--border)",
        boxShadow:    "0 10px 40px -15px rgba(0,0,0,0.05)",
        borderRadius: "2rem",
      }}
    >
      <div className="flex flex-col items-center gap-5 py-6">

        {/* Animated progress dots */}
        <div className="flex items-end gap-1.5">
          {[0, 1, 2, 3, 4, 5, 6].map((i) => (
            <motion.span
              key={i}
              animate={{ scaleY: [0.4, 1, 0.4], opacity: [0.35, 1, 0.35] }}
              transition={{
                repeat:   Infinity,
                duration: 1.1,
                delay:    i * 0.11,
                ease:     "easeInOut",
              }}
              style={{
                display:      "inline-block",
                width:        "6px",
                height:       i % 2 === 0 ? "18px" : "12px",
                borderRadius: "9999px",
                background:   i % 3 === 2
                  ? "var(--morandi-pink)"
                  : "var(--morandi-green)",
                transformOrigin: "bottom",
              }}
            />
          ))}
        </div>

        {/* Skeleton rows */}
        <div className="w-full flex flex-col gap-3 mt-1">
          {[100, 82, 92, 68].map((w, i) => (
            <motion.div
              key={i}
              animate={{ opacity: [0.3, 0.65, 0.3] }}
              transition={{ repeat: Infinity, duration: 1.5, delay: i * 0.18, ease: "easeInOut" }}
              className="h-11 rounded-2xl"
              style={{ width: `${w}%`, background: "var(--border)" }}
            />
          ))}
        </div>
      </div>
    </motion.div>
  );
}
